"""Go 侧 schema 快照的唯一生成器（T6-03：迁移单一化）。

产物是 `go-core/db/schema/` 下的三份只读快照 + 一份逐字节指纹：

    0001_legacy_auth.sql        public.users / public.refresh_tokens
    0002_canonical_runtime.sql  alembic 件 c8a2e4b6d0f2 的 _TABLES（21 张 canonical）
    0003_outbox_messages.sql    alembic 件 d9b1f3a5c7e9 的 _TABLES（outbox_messages）
    body.sha256                 每份快照 DDL 主体的 sha256（Go 闸门无 PG 也能逐字节判红）

**DDL 属主只有一个：`backend/alembic/`。** 本脚本不参与迁移，只做两件事——
把 alembic 链应用到一次性空库（`alembic upgrade head`），再把结果导出成快照。
表清单也不由人抄：0002/0003 的名单直接读迁移件里的 `_TABLES`，加一张 canonical 表
不需要动本脚本；改了 alembic 而忘了重跑本脚本，会被 `--check` 与两份闸门判红。

用法（默认＝从 alembic 重建）：

    .venv/bin/python scripts/export_pg_schema.py --docker closenai-pg-dev
    .venv/bin/python scripts/export_pg_schema.py --docker closenai-pg-dev --check
    .venv/bin/python scripts/export_pg_schema.py --check          # 本机装有 pg_dump 时
    .venv/bin/python scripts/export_pg_schema.py --only 0002_canonical_runtime.sql
    .venv/bin/python scripts/export_pg_schema.py --print-targets  # 不碰库，只打印名单

`--no-rebuild` 保留旧口径（直接从既有库导出、不重跑 alembic）：CI 里那条链由作业自己
`upgrade head`，本机历史上也用 `--docker closenai-pg-dev` dump 那台 `closenai` 库。
走没走重建都会写进文件头的 `source:` 行，出处不靠回忆。

连接串默认取 TEST_DATABASE_URL / DATABASE_URL / settings.database_url；SQLAlchemy 的
带驱动 scheme 一律译成 libpq 的 postgresql://（规则本体在 backend/core/pg_scheme.py，
Go 侧对应 internal/dsn）。pg_dump 16.9+ 会在开头插入一次性 `\restrict <随机 token>`，
它每次导出都不同，因此脚本会剔除这类行，保证快照可复现。比较（`--check` 与「主体未变」判定）
另外摘掉 `-- Dumped from database version` / `-- Dumped by pg_dump version` 两行环境签名：
换一台 pg_dump minor 不同的机器不该报漂移，而逐字节指纹闸仍按原字节算，环境行真变了照样红。
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import os
import re
import subprocess
import sys
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_DIR = ROOT / "go-core" / "db" / "schema"
CHECKSUM_NAME = "body.sha256"
EXPORT_DB = "closenai_schema_export"
BODY_MARKER = "--\n-- PostgreSQL database dump"
PSQL_META_RE = re.compile(r"^\\(restrict|unrestrict)\b")
# 「Dumped from database version 16.15 (Debian ...)」与「Dumped by pg_dump version ...」这两行
# 是**宿主环境**的签名，不是表结构。CI 的 runner 装的是发行版自带的 pg_dump，本机走的是容器里
# 那一份，版本号天生不同；若把它们计入主体比较，`--check` 会在换机器时假报漂移。
# 归一化只用于比较（见 env_normalized），写盘与指纹仍按原字节——逐字节闸 ④ 不会因为这里松一格
# 而失效：环境行变了照样红，只是「换一台 pg_dump minor 不同的机器」不算变更。
DUMP_ENV_RE = re.compile(r"^-- Dumped (from database|by pg_dump) version ")
DO_NOT_EDIT = ("-- DO NOT EDIT: generated by scripts/export_pg_schema.py from the "
               "alembic chain (T6-03).")

ALEMBIC_VERSIONS = ROOT / "backend" / "alembic" / "versions"
# 快照文件 → 声明这批表的 alembic 迁移件。名单取自件里的 _TABLES，不在此抄一遍。
TABLE_SOURCE_MIGRATIONS = {
    "0002_canonical_runtime.sql": "c8a2e4b6d0f2_add_canonical_runtime_tables.py",
    "0003_outbox_messages.sql": "d9b1f3a5c7e9_add_outbox_messages.py",
}
# 0001 是 legacy 面：这两张表建在 initial_schema / auth 件里，没有 _TABLES 约定可读，
# 所以按表点名并注明属主件。这一格是**白名单**（Go 工具链要读哪些 legacy 表），
# 不是 DDL 副本——副本正是本票要消灭的东西。
LEGACY_TABLES = ("public.users", "public.refresh_tokens")
LEGACY_OWNERS = ("users owned by 41cb43e22901, refresh_tokens by d1e3f5a7b9c2")
SNAPSHOT_ORDER = ("0001_legacy_auth.sql", "0002_canonical_runtime.sql",
                  "0003_outbox_messages.sql")


# ── 表名单：从 alembic 推导 ─────────────────────────────────────────────────


def alembic_tables(migration_file: str) -> tuple[str, ...]:
    """读迁移件的 `_TABLES` 拿表名——名单的唯一真源在 alembic 侧。"""
    path = ALEMBIC_VERSIONS / migration_file
    spec = importlib.util.spec_from_file_location(f"export_{path.stem}", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    tables = getattr(module, "_TABLES", None)
    if not tables:
        raise SystemExit(f"{migration_file} 没有 _TABLES，表清单取不到（别在这里抄一份）")
    return tuple(f"public.{name}" for name, _body in tables)


def snapshot_targets() -> dict[str, tuple[str, ...]]:
    """每份快照导哪些表。顺序按字母序稳定（pg_dump 本来就按这个名字序出主体）。"""
    out: dict[str, tuple[str, ...]] = {}
    for filename in SNAPSHOT_ORDER:
        migration = TABLE_SOURCE_MIGRATIONS.get(filename)
        tables = alembic_tables(migration) if migration else LEGACY_TABLES
        out[filename] = tuple(sorted(tables))
    return out


# ── 取数口径：重建 or 复用既有库 ────────────────────────────────────────────


@dataclass
class Source:
    """一份快照的出处：在哪里跑 pg_dump、alembic 往哪个库升级、文件头怎么写。"""

    docker: str | None
    dbname: str
    connect_url: str | None  # 主机侧可用的 libpq 串（psycopg / 本机 pg_dump）
    note: str

    @property
    def dump_url(self) -> str:
        if self.docker:
            return f"postgresql://postgres@{self.dbname}"
        assert self.connect_url, "非 docker 口径需要主机侧连接串"
        return self.connect_url


def libpq(url: str) -> str:
    sys.path.insert(0, str(ROOT))
    from backend.core.pg_scheme import libpq_url

    return libpq_url(url)


def psycopg_url_of(url: str) -> str:
    sys.path.insert(0, str(ROOT))
    from backend.core.pg_scheme import psycopg_url

    return psycopg_url(url)


def with_dbname(url: str, dbname: str) -> str:
    parts = urlsplit(url)
    return urlunsplit((parts.scheme, parts.netloc, f"/{dbname}", parts.query, parts.fragment))


def admin_url_of(url: str) -> str:
    """换成同主机同口令的维护库（postgres）——建/删一次性库要在这里下命令。"""
    return with_dbname(psycopg_url_of(url), "postgres")


def base_url(args: argparse.Namespace) -> str:
    raw = (args.database_url or os.environ.get("SCHEMA_EXPORT_SOURCE")
            or os.environ.get("TEST_DATABASE_URL") or os.environ.get("DATABASE_URL"))
    return libpq(raw) if raw else _settings_url()


def resolve_source(args: argparse.Namespace) -> Source:
    """alembic 升级的目标库 + pg_dump 的执行位置。"""
    source = base_url(args)
    if args.docker:
        return _docker_source(args, source)
    if not args.rebuild:
        return Source(None, source.rsplit("/", 1)[-1], source,
                      f"existing database from env/settings, alembic not re-run (--no-rebuild)")
    admin = admin_url_of(source)
    _admin_exec(admin, f"DROP DATABASE IF EXISTS {args.db_name}",
                f"CREATE DATABASE {args.db_name}")
    target = with_dbname(admin, args.db_name)
    _alembic_upgrade(libpq(target))
    return Source(None, args.db_name, libpq(target),
                  f"alembic upgrade head into {args.db_name} (rebuilt for this export)")


def _docker_source(args: argparse.Namespace, source: str) -> Source:
    dbname = args.db_name if args.rebuild else (source.rsplit("/", 1)[-1] or "closenai")
    if args.rebuild:
        _docker_db(args.docker, dbname)
        _alembic_upgrade(libpq(with_dbname(source, dbname)))
        note = (f"alembic upgrade head into {dbname} from the host, "
                f"dumped inside container {args.docker}")
    else:
        note = (f"existing database {dbname} inside container {args.docker} "
                "(--no-rebuild)")
    return Source(args.docker, dbname, libpq(with_dbname(source, dbname)), note)


def _docker_db(docker: str, dbname: str) -> None:
    for cmd in (["docker", "exec", docker, "dropdb", "-U", "postgres", "--if-exists", dbname],
                ["docker", "exec", docker, "createdb", "-U", "postgres", dbname]):
        proc = subprocess.run(cmd, capture_output=True, text=True)
        if proc.returncode != 0:
            raise SystemExit(f"{cmd[2]} 失败: {proc.stderr.strip()[:300]}")


def _admin_exec(admin: str, *statements: str) -> None:
    import psycopg

    with psycopg.connect(admin, autocommit=True) as conn:
        for sql in statements:
            conn.execute(sql)


def _alembic_upgrade(database_url: str) -> None:
    proc = subprocess.run(
        [sys.executable, "-m", "alembic", "-c", str(ROOT / "backend" / "alembic.ini"),
         "upgrade", "head"],
        cwd=ROOT, capture_output=True, text=True,
        env={**os.environ, "DATABASE_URL": psycopg_url_of(database_url)},
    )
    if proc.returncode != 0:
        raise SystemExit(f"alembic upgrade head 失败：\n{proc.stdout}\n{proc.stderr}")


def dump(src: Source, tables: tuple[str, str, ...]) -> str:
    args = ["pg_dump", "--schema-only", "--no-owner", "--no-privileges"]
    for table in tables:
        args += ["-t", table]
    if src.docker:
        cmd = ["docker", "exec", src.docker, *args, "-U", "postgres", "-d", src.dbname]
    else:
        cmd = [*args, src.dump_url]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        raise SystemExit(f"pg_dump 失败: {proc.stderr.strip()[:400]}")
    return proc.stdout


def alembic_head(src: Source) -> str:
    sql = "select version_num from public.alembic_version"
    if src.docker:
        proc = subprocess.run(["docker", "exec", src.docker, "psql", "-U", "postgres",
                               "-d", src.dbname, "-Atc", sql], capture_output=True, text=True)
        return proc.stdout.strip() if proc.returncode == 0 else "unknown"
    try:
        import psycopg

        with psycopg.connect(psycopg_url_of(src.connect_url)) as conn:
            return conn.execute(sql).scalar() or "unknown"
    except Exception:  # noqa: BLE001 - 取不到 head 只降级 provenance，不降级判据
        return "unknown"


def strip_psql_meta(raw: str) -> str:
    body = raw[raw.index(BODY_MARKER):]
    kept = [line for line in body.splitlines() if not PSQL_META_RE.match(line)]
    while kept and not kept[-1].strip():
        kept.pop()
    return "\n".join(kept) + "\n"


def body_of(text: str) -> str | None:
    at = text.find(BODY_MARKER)
    return None if at < 0 else text[at:]


def env_normalized(body: str | None) -> str:
    """比较用的主体：摘掉两行宿主环境签名（见 DUMP_ENV_RE）。指纹与写盘仍走原字节。"""
    if body is None:
        return ""
    return "".join(line + "\n" for line in body.splitlines()
                   if not DUMP_ENV_RE.match(line))


def header(src: Source, tables: tuple[str, ...], captured: str, head: str,
           filename: str, migration: str | None) -> str:
    owner = (f"-- Table list derived from alembic {migration} (_TABLES)."
             if migration else f"-- Legacy whitelist: {LEGACY_OWNERS}.")
    return f"""{DO_NOT_EDIT}
-- Provenance: pg_dump of the PostgreSQL 16 database produced by `alembic upgrade head`
--   source: {src.note}
--   command: {command_note(src, tables)}
--   captured: {captured}; alembic head revision {head}
-- DDL ownership is backend/alembic alone; this file is the read-only snapshot the
-- Go toolchain (sqlc) compiles against.
{owner}
-- Regenerate with scripts/export_pg_schema.py; do not hand-edit.
-- Hand-edits turn red in go-core/db/schema/drift_test.go ({filename})
-- and backend/tests/test_pg_schema_snapshot.py.

"""


def command_note(src: Source, tables: tuple[str, ...]) -> str:
    tail = " ".join(f"-t {t}" for t in tables)
    if src.docker:
        return (f"docker exec {src.docker} pg_dump -U postgres --schema-only "
                f"--no-owner --no-privileges {tail}")
    return f"pg_dump --schema-only --no-owner --no-privileges {tail}"


def render(src: Source, tables: tuple[str, ...], captured: str, filename: str) -> tuple[str, str]:
    body = strip_psql_meta(dump(src, tables))
    return header(src, tables, captured, alembic_head(src), filename,
                  TABLE_SOURCE_MIGRATIONS.get(filename)), body


# ── 逐字节指纹 ──────────────────────────────────────────────────────────────


def body_sha256(body: str) -> str:
    return hashlib.sha256(body.encode("utf-8")).hexdigest()


def checksum_map() -> dict[str, str]:
    path = SCHEMA_DIR / CHECKSUM_NAME
    out: dict[str, str] = {}
    if not path.exists():
        return out
    for line in path.read_text(encoding="utf-8").splitlines():
        if "  " in line and not line.startswith("--"):
            digest, name = line.split("  ", 1)
            out[name.strip()] = digest.strip()
    return out


def write_checksums() -> None:
    """指纹只覆盖 DDL 主体（表头有日期，逐日变）。三份快照都必须在清单里。"""
    known = checksum_map()
    for filename in SNAPSHOT_ORDER:
        path = SCHEMA_DIR / filename
        if not path.exists():
            continue
        body = body_of(path.read_text(encoding="utf-8"))
        if body:
            known[filename] = body_sha256(body)
    lines = [
        DO_NOT_EDIT,
        "-- Hash covers the DDL body only (from the PostgreSQL database dump marker to EOF).",
        "-- Written by scripts/export_pg_schema.py; compared byte-for-byte by",
        "-- go-core/db/schema/drift_test.go and backend/tests/test_pg_schema_snapshot.py.",
        "",
    ]
    lines += [f"{known[name]}  {name}" for name in SNAPSHOT_ORDER if name in known]
    (SCHEMA_DIR / CHECKSUM_NAME).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{CHECKSUM_NAME}: {sum(1 for name in SNAPSHOT_ORDER if name in known)} 条指纹")


def check_checksums() -> list[str]:
    known = checksum_map()
    bad: list[str] = []
    for filename in SNAPSHOT_ORDER:
        path = SCHEMA_DIR / filename
        if not path.exists():
            continue
        body = body_of(path.read_text(encoding="utf-8"))
        if body is None or known.get(filename) != body_sha256(body):
            bad.append(filename)
    return bad


# ── CLI ─────────────────────────────────────────────────────────────────────


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--docker", help="在指定容器内执行 pg_dump/psql/createdb")
    parser.add_argument("--database-url", default=None,
                        help="缺省读 SCHEMA_EXPORT_SOURCE/TEST_DATABASE_URL/DATABASE_URL/"
                             "settings.database_url")
    parser.add_argument("--db-name", default=EXPORT_DB,
                        help="重建时的一次性库名（默认 %s）" % EXPORT_DB)
    parser.add_argument("--no-rebuild", dest="rebuild", action="store_false",
                        help="直接从既有库导出，不重跑 alembic（旧口径；文件头会注明）")
    parser.set_defaults(rebuild=True)
    parser.add_argument("--only", action="append", dest="only",
                        help="可重复；只处理指定快照文件")
    parser.add_argument("--check", action="store_true",
                        help="只比对 DDL 主体（表头日期/revision 不参与比较）")
    parser.add_argument("--refresh-headers", action="store_true",
                        help="主体未变也重写表头（provenance 改了口径时用一次）")
    parser.add_argument("--print-targets", action="store_true",
                        help="打印每份快照的表白名单与来源，不碰库")
    args = parser.parse_args()

    targets = snapshot_targets()
    if args.print_targets:
        for filename, tables in targets.items():
            src_name = TABLE_SOURCE_MIGRATIONS.get(filename) or "LEGACY_TABLES"
            print(f"{filename}\t{len(tables)} tables\tfrom {src_name}")
        return

    selected = args.only or list(SNAPSHOT_ORDER)
    for filename in selected:
        if filename not in targets:
            raise SystemExit(f"未知快照 {filename}；已知 {', '.join(targets)}")

    if args.check:
        for filename in selected:
            if not (SCHEMA_DIR / filename).exists():
                raise SystemExit(f"MISSING {SCHEMA_DIR / filename}")

    src = resolve_source(args)
    captured = date.today().isoformat()
    drift: list[str] = []
    for filename in selected:
        new_header, new_body = render(src, targets[filename], captured, filename)
        path = SCHEMA_DIR / filename
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        old_body = body_of(current)
        if args.check:
            if env_normalized(old_body) != env_normalized(new_body):
                drift.append(filename)
                print(f"DRIFT {filename}: rerun scripts/export_pg_schema.py")
            else:
                print(f"{filename}: DDL 主体一致（{len(new_body.splitlines())} 行, "
                      f"tables={len(targets[filename])}）")
            continue
        if (env_normalized(old_body) == env_normalized(new_body) and not args.refresh_headers
                and DO_NOT_EDIT in current.split(BODY_MARKER, 1)[0]):
            print(f"{filename}: 未变（{len(new_body.splitlines())} 行），保留原表头"
                  "与环境版本行")
            continue
        # 主体一样但表头还是旧口径（没有 DO NOT EDIT / source 行）也要换头。
        path.write_text(new_header + new_body, encoding="utf-8")
        print(f"{filename}: {'表头更新' if old_body == new_body else '重写'}"
              f"（{len(new_body.splitlines())} 行, tables={len(targets[filename])}）")

    if args.check:
        if drift:
            raise SystemExit(f"DRIFT {len(drift)} 份: {', '.join(drift)}")
        bad = check_checksums()
        if bad:
            raise SystemExit(f"DRIFT {CHECKSUM_NAME}: {', '.join(bad)} 与文件不符"
                             "（rerun scripts/export_pg_schema.py）")
        print(f"DDL 主体一致：{len(selected)} 份快照 + 指纹清单（比较时摘掉宿主版本签名两行）")
        return
    write_checksums()


def _settings_url() -> str:
    sys.path.insert(0, str(ROOT))
    from backend.config import settings

    return libpq(settings.database_url)


if __name__ == "__main__":
    main()
