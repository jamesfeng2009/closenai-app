LOCALES = list(COPY)


def main() -> None:
    en = COPY["en"]
    assert len(LOCALES) == 15, f"语言清单 {len(LOCALES)} 个"
    for loc, block in COPY.items():
        assert list(block) == ORDER, f"{loc} 键序/键集与 ORDER 不一致"
        for key in ORDER:
            value = block[key]
            assert value.strip(), f"{loc}.{key} 是空串"
            assert set(_PLACEHOLDER.findall(value)) == set(_PLACEHOLDER.findall(en[key])), (
                f"{loc}.{key} 的占位符与 en 不一致"
            )
            if loc != "en":
                assert value != en[key], f"{loc}.{key} 逐字等于英文"
            # 前缀只许「冒号」或「冒号+一个空格」收尾：代码不再插分隔符，
            # 少一个空格就存出「This isn't mehello」这样的成长记录（见模块文档）。
            # 半角还是全角冒号由该语言的书写习惯定，这里不替 15 种语言做主。
            if key == "correctionPrefix":
                assert re.search(r"[:：] ?$", value), f"{loc}.{key} 不是冒号收尾：{value!r}"
                assert not value.endswith("  "), f"{loc}.{key} 有双尾空格"
            assert '"' not in value and "\\" not in value, f"{loc}.{key} 会破 TS 字符串"

    for loc in LOCALES:
        path = LOCALES_DIR / f"{loc}.ts"
        text = path.read_text(encoding="utf-8")
        assert '"moodAnalysis": {' not in text, f"{loc} 已有 moodAnalysis 段，脚本只许跑一次"
        # 15 份文件的收尾形状实测完全一致（末段的 `  }` + `};` + 默认导出）；
        # 不以此断言开头就动刀，拼错了会把整份 locale 变成语法错的文件。
        tail = "  }\n};\n\nexport default resource;\n"
        assert text.endswith(tail), f"{loc} 结尾形状与预期不符，脚本不动这个文件"
        body = text[: -len(tail)]
        lines = [f'    "{key}": "{COPY[loc][key]}"' for key in ORDER]
        section = '  "moodAnalysis": {\n' + ",\n".join(lines) + "\n  }\n"
        path.write_text(
            body + "  },\n" + section + "};\n\nexport default resource;\n", encoding="utf-8"
        )
        print(f"{loc}: moodAnalysis 段 +{len(ORDER)} 键")


if __name__ == "__main__":
    main()
