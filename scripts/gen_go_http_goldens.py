"""Regenerate go-core/testdata/http_golden.json.

Replays a set of requests against the running FastAPI app (in-process, no network,
no database: every case here fails request validation or is /health, so no handler
body ever runs) and records the exact status + response text. The Go side replays
the same requests and must produce byte-identical bodies.

Run:  .venv/bin/python scripts/gen_go_http_goldens.py
"""
from __future__ import annotations

import asyncio
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.database import get_db  # noqa: E402
from backend.main import app  # noqa: E402
from httpx import ASGITransport, AsyncClient  # noqa: E402

TRACE = "00000000-0000-0000-0000-000000000001"
BASE = {"email": "a@b.co", "username": "ok_user", "password": "abc12345"}

CASES: list[tuple[str, str, str, object]] = [
    ("health", "GET", "/health", None),
    ("register-empty-body", "POST", "/api/v1/auth/register", {}),
    ("register-email-pattern", "POST", "/api/v1/auth/register",
     {"email": "not-an-email", "username": "ab", "password": "12345678"}),
    ("register-username-too-long", "POST", "/api/v1/auth/register",
     {"email": "a@b.co", "username": "x" * 51, "password": "abc12345"}),
    ("register-username-bad-pattern", "POST", "/api/v1/auth/register",
     {**BASE, "username": "bad user!"}),
    ("register-password-too-short", "POST", "/api/v1/auth/register",
     {**BASE, "password": "abc123"}),
    ("register-email-type", "POST", "/api/v1/auth/register", {**BASE, "email": 123}),
    ("register-email-null", "POST", "/api/v1/auth/register", {**BASE, "email": None}),
    ("register-language-unsupported", "POST", "/api/v1/auth/register", {**BASE, "language": "xx"}),
    ("register-language-type", "POST", "/api/v1/auth/register", {**BASE, "language": 5}),
    ("register-ref-too-long", "POST", "/api/v1/auth/register", {**BASE, "ref": "A" * 17}),
    ("register-ref-type", "POST", "/api/v1/auth/register", {**BASE, "ref": 123}),
    ("register-ref-null-with-bad-username", "POST", "/api/v1/auth/register",
     {**BASE, "username": "ab", "ref": None}),
    ("register-unknown-key-only", "POST", "/api/v1/auth/register", {"nope": 1}),
    ("login-empty-body", "POST", "/api/v1/auth/login", {}),
    ("login-empty-password", "POST", "/api/v1/auth/login", {"identifier": "x", "password": ""}),
    ("login-identifier-too-long", "POST", "/api/v1/auth/login",
     {"identifier": "x" * 256, "password": "y"}),
    ("login-identifier-null", "POST", "/api/v1/auth/login", {"identifier": None, "password": "y"}),
    ("login-array-body", "POST", "/api/v1/auth/login", ["a"]),
]

RAW_BODY_CASES: list[tuple[str, str, str, bytes, str]] = [
    ("register-empty-raw", "POST", "/api/v1/auth/register", b"", "application/json"),
    ("login-not-json", "POST", "/api/v1/auth/login", b"not json", "application/json"),
    ("login-trailing-garbage", "POST", "/api/v1/auth/login",
     b'{"identifier":"x","password":"y"} x', "application/json"),
]


async def _db_override():
    yield None


async def _record() -> list[dict]:
    app.dependency_overrides[get_db] = _db_override
    recorded = []
    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://test") as client:
        for name, method, path, body in CASES:
            # Bodies go out compact so the recorded `input` echo (which Python
            # re-serialises compact) equals the request bytes Go echoes verbatim.
            headers = {"X-Trace-Id": TRACE}
            kwargs: dict = {}
            if body is not None:
                headers["Content-Type"] = "application/json"
                kwargs["content"] = json.dumps(body, separators=(",", ":"), ensure_ascii=False).encode()
            resp = await client.request(method, path, headers=headers, **kwargs)
            raw = kwargs.get("content")
            recorded.append(_entry(name, method, path, body, resp,
                                   raw.decode() if raw is not None else None))
        for name, method, path, raw, ctype in RAW_BODY_CASES:
            resp = await client.request(method, path, content=raw,
                                        headers={"X-Trace-Id": TRACE, "Content-Type": ctype})
            recorded.append(_entry(name, method, path, raw.decode(), resp, raw.decode()))
    return recorded


async def main() -> None:
    recorded = await _record()
    out = ROOT / "go-core" / "testdata" / "http_golden.json"
    payload = json.dumps({
        "_comment": "generated by scripts/gen_go_http_goldens.py; do not hand-edit",
        "trace_id": TRACE,
        "cases": recorded,
    }, indent=2, ensure_ascii=False) + "\n"
    if _check_mode():
        if not out.exists():
            print(f"MISSING {out}", file=sys.stderr)
            raise SystemExit(1)
        if out.read_text(encoding="utf-8") != payload:
            print(f"DRIFT {out}: rerun `python scripts/gen_go_http_goldens.py`",
                  file=sys.stderr)
            raise SystemExit(1)
        print(f"{out}: {len(recorded)} cases unchanged")
        return
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(payload, encoding="utf-8")
    print(f"{out}: {len(recorded)} cases")


def _check_mode() -> bool:
    return "--check" in sys.argv[1:]


def _entry(name, method, path, body, resp, request_raw=None) -> dict:
    return {
        "name": name,
        "method": method,
        "path": path,
        "request_body": body,
        # replayed verbatim by the Go test, so `input` echoes match byte-for-byte
        "request_raw": request_raw,
        "status": resp.status_code,
        "response_text": resp.text,
    }


if __name__ == "__main__":
    asyncio.run(main())
