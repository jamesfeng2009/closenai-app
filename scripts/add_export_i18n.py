ORDER = [
    "title", "desc", "descNoRetention", "request", "inProgress", "download",
    "statusQueued", "statusRunning", "statusReady", "statusFailed", "statusExpired",
    "unavailable", "notReady", "tooFrequent", "artifactMissing", "failedGeneric",
]


def render(lang: str, copy: dict[str, str]) -> str:
    lines = ['  "export": {']
    for key in ORDER:
        lines.append(f'    "{key}": "{copy[key]}"' + ("," if key != ORDER[-1] else ""))
    lines.append("  },")
    return "\n".join(lines) + "\n"


def main() -> None:
    for lang, copy in COPY.items():
        assert set(copy) == set(ORDER), f"{lang} 键集与 ORDER 不一致：{set(copy) ^ set(ORDER)}"
        path = LOCALES / f"{lang}.ts"
        text = path.read_text(encoding="utf-8")
        assert '"export": {' not in text, f"{lang} 已有 export 段，脚本只许跑一次"
        anchor = '  "help": {\n'
        assert text.count(anchor) == 1, f"{lang} 锚点 '  \"help\": {{' 出现 {text.count(anchor)} 次"
        block = render(lang, copy)
        for value in copy.values():
            assert '"' not in value, f"{lang} 的值里有裸双引号，会破 TS 字符串：{value[:40]}"
        path.write_text(text.replace(anchor, block + anchor), encoding="utf-8")
        print(f"{lang}: +{len(ORDER)} 键")


if __name__ == "__main__":
    main()
