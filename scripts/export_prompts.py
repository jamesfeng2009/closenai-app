#!/usr/bin/env python3
"""KG-26 §6.1.5：站点用的提示清单从同一份 JSON 生成，不在站点里手写第二份 30 条。

输出 `docs/content/drafts/journal-prompts.<lang>.md`。这两份 .md 是**草稿**，不是线上页面
（上线属 KG-12），但它们是那条禁令的机器证人：

    python scripts/export_prompts.py --check   # 内容与 JSON 不一致就非零退出

`--check` 给 CI 用；不带它才写文件。产出走 `prompt_library.library()`，
它在内容校验不过时直接抛 `PromptLibraryError`——半坏的库比没有库更容易被抄进站点。
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import List

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.services import prompt_library  # noqa: E402

OUT_DIR = ROOT / "docs" / "content" / "drafts"

ZH_HEADER = "# 反思提示\n\n本文件由 `scripts/export_prompts.py` 从 `backend/content/reflection_prompts.json` 生成，**不要手改**：改内容请改那份 JSON（它是唯一真源），然后重跑脚本。\n"
EN_HEADER = (
    "# Reflection prompts\n\n"
    "Generated by `scripts/export_prompts.py` from `backend/content/reflection_prompts.json`. "
    "**Do not edit by hand** — that JSON is the single source; change it and re-run the script.\n"
)


def render(language: str) -> str:
    payload = prompt_library.list_prompts(language=language)
    by_cluster: dict[str, List[dict]] = {}
    for row in payload["prompts"]:
        by_cluster.setdefault(row["cluster"], []).append(row)

    lines: List[str] = [
        (ZH_HEADER if payload["language_used"] == "zh" else EN_HEADER).rstrip("\n"),
        "",
        f"version: `{payload['version']}` · language: `{payload['language_used']}` · "
        f"prompts: {payload['total']} · clusters: {len(payload['clusters'])}",
        "",
    ]
    registered = [c["key"] for c in payload["clusters"]]
    for meta in payload["clusters"]:
        rows = sorted(by_cluster.get(meta["key"], []), key=lambda p: p["id"])
        lines.append(f"## {meta['title']}")
        if meta["hint"]:
            lines.append(f"_{meta['hint']}_")
        lines.append("")
        for row in rows:
            lines.append(f"### {row['id']} · {row['title']}")
            lines.append("")
            lines.append(f"- {row['question']}")
            if row["why"]:
                lines.append(f"- why: {row['why']}")
            if row["follow_up"]:
                lines.append(f"- follow-up: {row['follow_up']}")
            lines.append("")
    # 簇改名后残留的提示单列出来，而不是静默丢掉：草稿少几条＝站点少几页可抓的内容
    for key in [k for k in sorted(by_cluster) if k not in registered]:
        lines.append(f"## {key}（未登记簇）")
        lines.append("")
        for row in sorted(by_cluster[key], key=lambda p: p["id"]):
            lines.append(f"### {row['id']} · {row['title']}")
            lines.append("")
            lines.append(f"- {row['question']}")
            lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="从提示库 JSON 生成站点草稿")
    parser.add_argument("--check", action="store_true", help="只比对，不写文件；不一致则非零退出")
    args = parser.parse_args()

    try:
        prompt_library.library()
    except prompt_library.PromptLibraryError as exc:
        print("提示库内容校验未过，不产出草稿：")
        for item in exc.problems:
            print(f"  - {item}")
        return 1

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    exit_code = 0
    total = len(prompt_library.library()["prompts"])
    for language in prompt_library.LIBRARY_LANGUAGES:
        path = OUT_DIR / f"journal-prompts.{language}.md"
        text = render(language)
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != text:
                print(f"{path.relative_to(ROOT)} 与 JSON 不一致，请重跑 export_prompts.py")
                exit_code = 1
            else:
                print(f"{path.relative_to(ROOT)} 一致")
            continue
        path.write_text(text, encoding="utf-8")
        print(f"{path.relative_to(ROOT)} 已写出（{total} 条）")
    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
