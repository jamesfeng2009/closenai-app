"""Regenerate go-core/testdata/python_auth_baseline.json.

The Go side cannot be trusted to *interpret* Python's auth primitives, so the
fixtures are produced by the real functions in backend/core/auth.py (argon2-cffi
and PyJWT, with backend's own utc_now frozen) and then verified by `go test`.

Run:  .venv/bin/python scripts/gen_go_auth_fixtures.py
"""
from __future__ import annotations

import json
import pathlib
import sys
from datetime import datetime, timedelta, timezone

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.core.auth import (  # noqa: E402
    create_access_token,
    create_refresh_token,
    hash_password,
    hash_refresh_token,
    verify_password,
)

TEST_SECRET = "cross-language-test-secret"
# Frozen in the future on purpose: PyJWT/Go both reject an expired exp, so a
# "now"-relative fixture would expire 30 minutes after it is generated.
FROZEN_NOW = datetime(2030, 1, 1, 0, 0, 0, tzinfo=timezone.utc)
# The expired fixture has to be expired relative to *real* now, not FROZEN_NOW.
EXPIRED_NOW = datetime(2020, 1, 1, 0, 0, 0, tzinfo=timezone.utc)
PASSWORDS = ["passw0rd", "correct horse battery staple 1", "中文密码测试1"]
USER_ID = "7f0f6b2c-1c3b-4a5e-9d2a-3b4c5d6e7f80"
TOKEN_ID = "aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee"


def build() -> dict:
    import backend.config

    backend.config.settings.jwt_secret = TEST_SECRET
    access = _patch_now(lambda: create_access_token(USER_ID))
    refresh = _patch_now(lambda: create_refresh_token(USER_ID, TOKEN_ID))
    expired = _patch_now(
        lambda: create_access_token(USER_ID), EXPIRED_NOW
    )

    return {
        "_comment": "generated by scripts/gen_go_auth_fixtures.py; do not hand-edit",
        "secret": TEST_SECRET,
        "algorithm": "HS256",
        "user_id": USER_ID,
        "token_id": TOKEN_ID,
        "frozen_now_epoch": int(FROZEN_NOW.timestamp()),
        "access_expire_minutes": 30,
        "refresh_expire_days": 30,
        "tokens": {
            "access": {
                "jwt": access,
                "sub": USER_ID,
                "type": "access",
                "iat": int(FROZEN_NOW.timestamp()),
                "exp": int((FROZEN_NOW + timedelta(minutes=30)).timestamp()),
            },
            "refresh": {
                "jwt": refresh,
                "sub": USER_ID,
                "jti": TOKEN_ID,
                "type": "refresh",
                "iat": int(FROZEN_NOW.timestamp()),
                "exp": int((FROZEN_NOW + timedelta(days=30)).timestamp()),
            },
            "expired_access": {
                "jwt": expired,
                "expect_error": "expired",
                "iat": int(EXPIRED_NOW.timestamp()),
                "exp": int((EXPIRED_NOW + timedelta(minutes=30)).timestamp()),
            },
            "wrong_secret_access": _sign_with(
                "not-the-agreed-secret",
                {"sub": USER_ID, "type": "access", "iat": int(FROZEN_NOW.timestamp()),
                 "exp": int((FROZEN_NOW + timedelta(minutes=30)).timestamp())},
            ),
            "tampered_access": access[:-2] + ("AA" if not access.endswith("AA") else "BB"),
        },
        "argon2id": {
            "expected_prefix": "$argon2id$v=19$m=65536,t=3,p=4$",
            "hashes": [
                {
                    "password": pwd,
                    "hash": hash_password(pwd),
                    "verify": verify_password(pwd, hash_password(pwd)),
                }
                for pwd in PASSWORDS
            ],
        },
        "refresh_token_hash": {
            "token": refresh,
            "sha256_hex": hash_refresh_token(refresh),
        },
    }


def _sign_with(secret: str, claims: dict) -> str:
    import jwt

    return jwt.encode(claims, secret, algorithm="HS256")


def _patch_now(fn, now: datetime = FROZEN_NOW) -> str:
    import backend.core.auth as auth_module

    original = auth_module.utc_now
    auth_module.utc_now = lambda: now
    try:
        return fn()
    finally:
        auth_module.utc_now = original


def main() -> None:
    payload = build()
    out = ROOT / "go-core" / "testdata" / "python_auth_baseline.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{out}: {len(payload['argon2id']['hashes'])} hashes, {len(payload['tokens'])} tokens")


if __name__ == "__main__":
    main()
